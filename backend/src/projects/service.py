from collections.abc import Mapping
from datetime import datetime, timezone
from typing import Any
from urllib.parse import urlparse
from uuid import uuid4

from src.projects.models import ProjectItem
from src.projects.repository import ConflictError, InvalidCursorError, ProjectRepository
from src.shared.auth import AuthenticatedIdentity
from src.shared.validation import ValidationError, require_json_object, require_string


class NotFoundError(LookupError):
    """Raised when a requested project does not exist."""


class ForbiddenError(PermissionError):
    """Raised when the authenticated user cannot view or change a project."""


DIFFICULTIES = {'Beginner', 'Intermediate', 'Advanced'}
PROJECT_ROLES = {'Developer', 'Designer', 'Tester', 'Contributor'}
MILESTONE_STATUSES = {'ACTIVE', 'IN_PROGRESS', 'COMPLETED'}
COMPLETION_CONFIRMATION_MODE = 'ALL_CURRENT_MEMBERS'
TASK_STATUSES = ('TODO', 'IN_PROGRESS', 'IN_REVIEW', 'COMPLETED')
TASK_PRIORITIES = {'LOW', 'MEDIUM', 'HIGH'}
TASK_TRANSITIONS = {
    'TODO': {'TODO', 'IN_PROGRESS'},
    'IN_PROGRESS': {'IN_PROGRESS', 'IN_REVIEW'},
    'IN_REVIEW': {'IN_REVIEW', 'COMPLETED'},
    'COMPLETED': {'COMPLETED'},
}


def _string_list(payload: Mapping[str, Any], field: str, *, minimum: int = 1, maximum: int = 20) -> list[str]:
    value = payload.get(field)
    if not isinstance(value, list) or not minimum <= len(value) <= maximum:
        raise ValidationError(f'{field} must contain between {minimum} and {maximum} items.')
    if not all(isinstance(item, str) and item.strip() for item in value):
        raise ValidationError(f'{field} must contain non-empty strings.')
    return [item.strip() for item in value]


def _project_response(item: Mapping[str, Any], *, details: bool = False) -> dict[str, Any]:
    allowed = {
        'id', 'title', 'description', 'technology', 'category', 'difficulty',
        'requiredRoles', 'capacity', 'memberCount', 'status', 'repositoryUrl',
        'createdAt', 'updatedAt',
    }
    if details:
        allowed.update({'fullDescription', 'goals', 'outcomes'})
    return {key: item[key] for key in allowed if key in item}


def _collaboration_response(item: Mapping[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in item.items() if key not in {'PK', 'SK', 'GSI1PK', 'GSI1SK'}}


class ProjectService:
    def __init__(self, repository: ProjectRepository) -> None:
        self.repository = repository

    def list_projects(self, identity: AuthenticatedIdentity, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], str | None]:
        del identity  # API Gateway authentication is required before this service is called.
        if not 1 <= limit <= 50:
            raise ValidationError('limit must be between 1 and 50.')
        projects, next_cursor = self.repository.list_public_projects(limit, cursor)
        public_projects = [project for project in projects if project.get('visibility', 'public') == 'public']
        return [_project_response(project) for project in public_projects], next_cursor

    def get_project(self, identity: AuthenticatedIdentity, project_id: str) -> dict[str, Any]:
        if not project_id or len(project_id) > 128:
            raise ValidationError('projectId is invalid.')
        project = self.repository.get_project(project_id)
        if project is None:
            raise NotFoundError('Project not found.')
        visibility = project.get('visibility', 'public')
        if visibility != 'public' and not self._is_member(project, identity.user_id):
            raise ForbiddenError('You cannot view this project.')
        response = _project_response(project, details=True)
        response['projectProgress'] = self._progress(self.repository.list_all_tasks(project_id))
        return response

    def create_project(self, identity: AuthenticatedIdentity, body: Any) -> dict[str, Any]:
        payload = require_json_object(body)
        if 'ownerId' in payload or 'owner_id' in payload:
            raise ValidationError('ownerId is derived from authentication and must not be supplied.')
        if 'id' in payload:
            raise ValidationError('id is generated by the service and must not be supplied.')

        title = require_string(payload, 'title', max_length=160)
        description = require_string(payload, 'description', max_length=500)
        full_description = require_string(payload, 'fullDescription', max_length=5000)
        category = require_string(payload, 'category', max_length=100)
        technology = _string_list(payload, 'technology')
        goals = _string_list(payload, 'goals', maximum=20)
        outcomes = _string_list(payload, 'outcomes', maximum=20)
        required_roles = _string_list(payload, 'requiredRoles', maximum=20)

        difficulty = payload.get('difficulty')
        if difficulty not in DIFFICULTIES:
            raise ValidationError('difficulty is invalid.')
        capacity = payload.get('capacity')
        if not isinstance(capacity, int) or isinstance(capacity, bool) or not 1 <= capacity <= 50:
            raise ValidationError('capacity must be an integer between 1 and 50.')

        status = payload.get('status', 'Recruiting')
        if status != 'Recruiting':
            raise ValidationError('New projects must start in Recruiting status.')
        repository_url = payload.get('repositoryUrl')
        if repository_url is not None:
            repository_url = require_string(payload, 'repositoryUrl', max_length=500)
            parsed = urlparse(repository_url)
            if parsed.scheme not in {'http', 'https'} or not parsed.netloc:
                raise ValidationError('repositoryUrl must be an http or https URL.')

        now = datetime.now(timezone.utc).isoformat()
        project_id = f'project-{uuid4().hex}'
        item: ProjectItem = {
            'PK': f'PROJECT#{project_id}',
            'SK': 'METADATA',
            'GSI1PK': ProjectRepository.PROJECT_INDEX_PARTITION,
            'GSI1SK': f'{now}#{project_id}',
            'id': project_id,
            'title': title,
            'description': description,
            'fullDescription': full_description,
            'goals': goals,
            'outcomes': outcomes,
            'ownerId': identity.user_id,
            'technology': technology,
            'category': category,
            'difficulty': difficulty,
            'requiredRoles': required_roles,
            'capacity': capacity,
            'memberCount': 1,
            'status': 'Recruiting',
            'visibility': 'public',
            'createdAt': now,
            'updatedAt': now,
        }
        if repository_url:
            item['repositoryUrl'] = repository_url
        self.repository.create_project(item, self._activity(project_id, 'PROJECT_CREATED', identity.user_id, now))
        return _project_response(item, details=True)

    def _project_for_collaboration(self, project_id: str) -> ProjectItem:
        if not project_id or len(project_id) > 128:
            raise ValidationError('projectId is invalid.')
        project = self.repository.get_project(project_id)
        if project is None:
            raise NotFoundError('Project not found.')
        return project

    @staticmethod
    def _role(payload: Mapping[str, Any]) -> str:
        role = payload.get('role', 'Contributor')
        if role not in PROJECT_ROLES:
            raise ValidationError('role is invalid.')
        return role

    @staticmethod
    def _reject_actor_fields(payload: Mapping[str, Any]) -> None:
        if any(field in payload for field in ('userId', 'requesterId', 'inviterId', 'ownerId')):
            raise ValidationError('Authenticated user identity must not be supplied by the client.')

    def create_join_request(self, identity: AuthenticatedIdentity, project_id: str, body: Any) -> dict[str, Any]:
        project = self._project_for_collaboration(project_id)
        payload = require_json_object(body)
        self._reject_actor_fields(payload)
        if project.get('ownerId') == identity.user_id:
            raise ForbiddenError('Project owners cannot request to join their own project.')
        if project.get('status') != 'Recruiting' or int(project.get('memberCount', 0)) >= int(project.get('capacity', 0)):
            raise ConflictError('This project is not accepting members.')
        now = datetime.now(timezone.utc).isoformat()
        request_id = f'join-{uuid4().hex}'
        item = {
            'PK': f'PROJECT#{project_id}', 'SK': f'{self.repository.JOIN_REQUEST_PREFIX}{request_id}',
            'entityType': 'join_request', 'id': request_id, 'projectId': project_id,
            'requesterId': identity.user_id, 'role': self._role(payload), 'status': 'pending',
            'createdAt': now, 'updatedAt': now,
        }
        self.repository.create_join_request(item)
        return _collaboration_response(item)

    def list_join_requests(self, identity: AuthenticatedIdentity, project_id: str) -> list[dict[str, Any]]:
        project = self._project_for_collaboration(project_id)
        if project.get('ownerId') != identity.user_id:
            raise ForbiddenError('Only the project owner can view join requests.')
        return [_collaboration_response(item) for item in self.repository.list_join_requests(project_id)]

    def review_join_request(self, identity: AuthenticatedIdentity, project_id: str, request_id: str, body: Any) -> dict[str, Any]:
        project = self._project_for_collaboration(project_id)
        if project.get('ownerId') != identity.user_id:
            raise ForbiddenError('Only the project owner can review join requests.')
        request = self.repository.get_join_request(project_id, request_id)
        if request is None:
            raise NotFoundError('Join request not found.')
        payload = require_json_object(body)
        action = payload.get('action')
        if action not in {'approve', 'reject'}:
            raise ValidationError('action must be approve or reject.')
        self._reject_actor_fields(payload)
        if request.get('status') != 'pending':
            raise ConflictError('Join request is no longer pending.')
        now = datetime.now(timezone.utc).isoformat()
        activity = self._activity(project_id, 'JOIN_REQUEST_APPROVED', identity.user_id, now, join_request_id=request_id)
        self.repository.review_join_request(project, request, action, now, activity if action == 'approve' else None)
        updated = dict(request)
        updated['status'] = 'approved' if action == 'approve' else 'rejected'
        updated['updatedAt'] = now
        return _collaboration_response(updated)

    def create_invitation(self, identity: AuthenticatedIdentity, project_id: str, body: Any) -> dict[str, Any]:
        project = self._project_for_collaboration(project_id)
        if project.get('ownerId') != identity.user_id:
            raise ForbiddenError('Only the project owner can send invitations.')
        payload = require_json_object(body)
        self._reject_actor_fields(payload)
        invitee_id = require_string(payload, 'inviteeId', max_length=256)
        if invitee_id == identity.user_id:
            raise ValidationError('You cannot invite yourself.')
        if project.get('status') != 'Recruiting' or int(project.get('memberCount', 0)) >= int(project.get('capacity', 0)):
            raise ConflictError('This project is not accepting members.')
        now = datetime.now(timezone.utc).isoformat()
        invitation_id = f'invite-{uuid4().hex}'
        item = {
            'PK': f'PROJECT#{project_id}', 'SK': f'{self.repository.INVITATION_PREFIX}{invitation_id}',
            'entityType': 'invitation', 'id': invitation_id, 'projectId': project_id,
            'inviteeId': invitee_id, 'role': self._role(payload), 'status': 'pending',
            'createdAt': now, 'updatedAt': now,
        }
        self.repository.create_invitation(item)
        return _collaboration_response(item)

    def list_invitations(self, identity: AuthenticatedIdentity, project_id: str) -> list[dict[str, Any]]:
        project = self._project_for_collaboration(project_id)
        invitations = self.repository.list_invitations(project_id)
        if project.get('ownerId') != identity.user_id:
            invitations = [item for item in invitations if item.get('inviteeId') == identity.user_id]
            if not invitations:
                raise ForbiddenError('You cannot view these invitations.')
        return [_collaboration_response(item) for item in invitations]

    def respond_invitation(self, identity: AuthenticatedIdentity, project_id: str, invitation_id: str, body: Any) -> dict[str, Any]:
        project = self._project_for_collaboration(project_id)
        invitation = self.repository.get_invitation(project_id, invitation_id)
        if invitation is None:
            raise NotFoundError('Invitation not found.')
        if invitation.get('inviteeId') != identity.user_id:
            raise ForbiddenError('Only the invited user can respond.')
        payload = require_json_object(body)
        action = payload.get('action')
        if action not in {'accept', 'decline'}:
            raise ValidationError('action must be accept or decline.')
        self._reject_actor_fields(payload)
        if invitation.get('status') != 'pending':
            raise ConflictError('Invitation is no longer pending.')
        now = datetime.now(timezone.utc).isoformat()
        activity = self._activity(project_id, 'INVITATION_ACCEPTED', identity.user_id, now, invitation_id=invitation_id)
        self.repository.respond_invitation(project, invitation, action, now, activity if action == 'accept' else None)
        updated = dict(invitation)
        updated['status'] = 'accepted' if action == 'accept' else 'declined'
        updated['updatedAt'] = now
        return _collaboration_response(updated)

    def list_members(self, identity: AuthenticatedIdentity, project_id: str) -> list[dict[str, Any]]:
        project = self._project_for_collaboration(project_id)
        if project.get('visibility', 'public') != 'public' and project.get('ownerId') != identity.user_id:
            raise ForbiddenError('You cannot view this team.')
        members = [{'projectId': project_id, 'userId': project.get('ownerId'), 'role': 'Owner', 'joinedAt': project.get('createdAt')}]
        members.extend(_collaboration_response(item) for item in self.repository.list_members(project_id))
        return members

    def _is_member(self, project: ProjectItem, user_id: str) -> bool:
        return project.get('ownerId') == user_id or self.repository.get_membership(project['id'], user_id) is not None

    def _require_project_access(self, identity: AuthenticatedIdentity, project_id: str) -> ProjectItem:
        project = self._project_for_collaboration(project_id)
        if project.get('visibility', 'public') != 'public' and not self._is_member(project, identity.user_id):
            raise ForbiddenError('You are not a member of this private project.')
        return project

    def _require_owner(self, identity: AuthenticatedIdentity, project_id: str) -> ProjectItem:
        project = self._project_for_collaboration(project_id)
        if project.get('ownerId') != identity.user_id:
            raise ForbiddenError('Only the project owner can manage this project.')
        return project

    @staticmethod
    def _optional_string(payload: Mapping[str, Any], field: str, maximum: int = 256) -> str | None:
        if field not in payload or payload[field] is None:
            return None
        return require_string(payload, field, max_length=maximum)

    @staticmethod
    def _progress(tasks: list[Mapping[str, Any]], milestone_id: str | None = None) -> dict[str, int | float]:
        selected = [task for task in tasks if milestone_id is None or task.get('milestoneId') == milestone_id]
        total = len(selected)
        completed = sum(1 for task in selected if task.get('status') == 'COMPLETED')
        return {'completedTasks': completed, 'totalTasks': total, 'percentage': round(completed / total * 100, 2) if total else 0}

    @staticmethod
    def _milestone_response(item: Mapping[str, Any], progress: Mapping[str, Any]) -> dict[str, Any]:
        return {**_collaboration_response(item), 'progress': dict(progress)}

    def list_milestones(self, identity: AuthenticatedIdentity, project_id: str, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], str | None]:
        self._require_project_access(identity, project_id)
        if not 1 <= limit <= 100:
            raise ValidationError('limit must be between 1 and 100.')
        milestones, next_cursor = self.repository.list_milestones(project_id, limit, cursor)
        tasks = self.repository.list_all_tasks(project_id)
        return [self._milestone_response(item, self._progress(tasks, item['milestoneId'])) for item in milestones], next_cursor

    def create_milestone(self, identity: AuthenticatedIdentity, project_id: str, body: Any) -> dict[str, Any]:
        project = self._require_owner(identity, project_id)
        del project
        payload = require_json_object(body)
        self._reject_actor_fields(payload)
        title = require_string(payload, 'title', max_length=160)
        description = self._optional_string(payload, 'description', 5000) or ''
        order = payload.get('order', 0)
        if not isinstance(order, int) or isinstance(order, bool) or order < 0:
            raise ValidationError('order must be a non-negative integer.')
        status = payload.get('status', 'ACTIVE')
        if status not in MILESTONE_STATUSES:
            raise ValidationError('status is invalid.')
        start_date = self._optional_string(payload, 'startDate')
        due_date = self._optional_string(payload, 'dueDate')
        now = datetime.now(timezone.utc).isoformat()
        milestone_id = f'milestone-{uuid4().hex}'
        item = {
            'PK': f'PROJECT#{project_id}', 'SK': f'{self.repository.MILESTONE_PREFIX}{milestone_id}',
            'entityType': 'milestone', 'milestoneId': milestone_id, 'projectId': project_id,
            'title': title, 'description': description, 'order': order, 'status': status,
            'createdBy': identity.user_id, 'createdAt': now, 'updatedAt': now,
        }
        if start_date:
            item['startDate'] = start_date
        if due_date:
            item['dueDate'] = due_date
        activity = self._activity(project_id, 'MILESTONE_CREATED', identity.user_id, now, milestone_id=milestone_id)
        self.repository.create_milestone(item, activity)
        return self._milestone_response(item, self._progress([], milestone_id))

    def update_milestone(self, identity: AuthenticatedIdentity, project_id: str, milestone_id: str, body: Any) -> dict[str, Any]:
        self._require_owner(identity, project_id)
        milestone = self.repository.get_milestone(project_id, milestone_id)
        if milestone is None:
            raise NotFoundError('Milestone not found.')
        payload = require_json_object(body)
        self._reject_actor_fields(payload)
        allowed = {'title', 'description', 'order', 'status', 'startDate', 'dueDate'}
        unknown = set(payload) - allowed
        if unknown:
            raise ValidationError('Only milestone fields may be updated.')
        updates: dict[str, Any] = {}
        if 'title' in payload:
            updates['title'] = require_string(payload, 'title', max_length=160)
        if 'description' in payload:
            updates['description'] = require_string(payload, 'description', max_length=5000)
        if 'order' in payload:
            if not isinstance(payload['order'], int) or isinstance(payload['order'], bool) or payload['order'] < 0:
                raise ValidationError('order must be a non-negative integer.')
            updates['order'] = payload['order']
        if 'status' in payload:
            if payload['status'] not in MILESTONE_STATUSES:
                raise ValidationError('status is invalid.')
            if payload['status'] == 'COMPLETED':
                milestone_tasks = [task for task in self.repository.list_all_tasks(project_id) if task.get('milestoneId') == milestone_id]
                if any(task.get('status') != 'COMPLETED' for task in milestone_tasks):
                    raise ConflictError('All milestone tasks must be completed first.')
            updates['status'] = payload['status']
        for field in ('startDate', 'dueDate'):
            if field in payload:
                updates[field] = self._optional_string(payload, field)
        if not updates:
            raise ValidationError('At least one milestone field is required.')
        now = datetime.now(timezone.utc).isoformat()
        updates['updatedAt'] = now
        activity = self._activity(project_id, 'MILESTONE_UPDATED', identity.user_id, now, milestone_id=milestone_id)
        updated = self.repository.update_milestone(milestone, updates, activity)
        tasks = self.repository.list_all_tasks(project_id)
        return self._milestone_response(updated, self._progress(tasks, milestone_id))

    def delete_milestone(self, identity: AuthenticatedIdentity, project_id: str, milestone_id: str) -> None:
        self._require_owner(identity, project_id)
        milestone = self.repository.get_milestone(project_id, milestone_id)
        if milestone is None:
            raise NotFoundError('Milestone not found.')
        tasks = self.repository.list_all_tasks(project_id)
        if any(task.get('milestoneId') == milestone_id for task in tasks):
            raise ConflictError('Milestones with dependent tasks cannot be deleted.')
        self.repository.delete_milestone(milestone)

    @staticmethod
    def _activity(
        project_id: str, event_type: str, actor_id: str, now: str, *, milestone_id: str | None = None,
        task_id: str | None = None, join_request_id: str | None = None, invitation_id: str | None = None,
    ) -> dict[str, Any]:
        activity_id = f'activity-{uuid4().hex}'
        item: dict[str, Any] = {
            'PK': f'PROJECT#{project_id}', 'SK': f'ACTIVITY#{now}#{activity_id}', 'entityType': 'activity',
            'activityId': activity_id, 'projectId': project_id, 'type': event_type,
            'actorId': actor_id, 'createdAt': now,
        }
        if milestone_id:
            item['milestoneId'] = milestone_id
        if task_id:
            item['taskId'] = task_id
        if join_request_id:
            item['joinRequestId'] = join_request_id
        if invitation_id:
            item['invitationId'] = invitation_id
        return item

    def _task_response(self, task: Mapping[str, Any], tasks: list[Mapping[str, Any]]) -> dict[str, Any]:
        progress = self._progress(tasks)
        result = {**_collaboration_response(task), 'projectProgress': progress}
        milestone_id = task.get('milestoneId')
        if milestone_id:
            result['milestoneProgress'] = self._progress(tasks, milestone_id)
        return result

    def list_tasks(self, identity: AuthenticatedIdentity, project_id: str, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], dict[str, Any], str | None]:
        self._require_project_access(identity, project_id)
        if not 1 <= limit <= 100:
            raise ValidationError('limit must be between 1 and 100.')
        tasks, next_cursor = self.repository.list_tasks(project_id, limit, cursor)
        all_tasks = self.repository.list_all_tasks(project_id)
        return [self._task_response(item, all_tasks) for item in tasks], self._progress(all_tasks), next_cursor

    def get_task(self, identity: AuthenticatedIdentity, project_id: str, task_id: str) -> dict[str, Any]:
        self._require_project_access(identity, project_id)
        task = self.repository.get_task(project_id, task_id)
        if task is None:
            raise NotFoundError('Task not found.')
        return self._task_response(task, self.repository.list_all_tasks(project_id))

    def create_task(self, identity: AuthenticatedIdentity, project_id: str, body: Any) -> dict[str, Any]:
        self._require_owner(identity, project_id)
        payload = require_json_object(body)
        self._reject_actor_fields(payload)
        title = require_string(payload, 'title', max_length=160)
        description = self._optional_string(payload, 'description', 5000) or ''
        status = payload.get('status', 'TODO')
        priority = payload.get('priority', 'MEDIUM')
        if status not in TASK_STATUSES:
            raise ValidationError('status is invalid.')
        if priority not in TASK_PRIORITIES:
            raise ValidationError('priority is invalid.')
        milestone_id = self._optional_string(payload, 'milestoneId', 128)
        milestone = None
        if milestone_id:
            milestone = self.repository.get_milestone(project_id, milestone_id)
            if milestone is None or milestone.get('status') == 'COMPLETED':
                raise ValidationError('milestoneId must reference an active milestone in this project.')
        assignee_id = self._optional_string(payload, 'assigneeId')
        if assignee_id and not self._is_member(self._project_for_collaboration(project_id), assignee_id):
            raise ValidationError('assigneeId must be a project member.')
        now = datetime.now(timezone.utc).isoformat()
        task_id = f'task-{uuid4().hex}'
        item: dict[str, Any] = {
            'PK': f'PROJECT#{project_id}', 'SK': f'{self.repository.TASK_PREFIX}{task_id}',
            'entityType': 'task', 'taskId': task_id, 'projectId': project_id,
            'title': title, 'description': description, 'status': status, 'priority': priority,
            'createdBy': identity.user_id, 'createdAt': now, 'updatedAt': now,
        }
        for field, value in (('milestoneId', milestone_id), ('assigneeId', assignee_id), ('dueDate', self._optional_string(payload, 'dueDate'))):
            if value:
                item[field] = value
        activities = [self._activity(project_id, 'TASK_CREATED', identity.user_id, now, task_id=task_id)]
        if assignee_id:
            activities.append(self._activity(project_id, 'TASK_ASSIGNED', identity.user_id, now, task_id=task_id))
        self.repository.create_task(item, activities, milestone)
        return self._task_response(item, [item])

    def update_task(self, identity: AuthenticatedIdentity, project_id: str, task_id: str, body: Any) -> dict[str, Any]:
        project = self._require_project_access(identity, project_id)
        task = self.repository.get_task(project_id, task_id)
        if task is None:
            raise NotFoundError('Task not found.')
        payload = require_json_object(body)
        self._reject_actor_fields(payload)
        is_owner = project.get('ownerId') == identity.user_id
        if not is_owner and task.get('assigneeId') != identity.user_id:
            raise ForbiddenError('Only the assignee or project owner can update this task.')
        allowed = {'title', 'description', 'milestoneId', 'assigneeId', 'status', 'priority', 'dueDate'}
        if not is_owner and set(payload) != {'status'}:
            raise ForbiddenError('Members may only update the status of their assigned task.')
        if set(payload) - allowed:
            raise ValidationError('Only task fields may be updated.')
        updates: dict[str, Any] = {}
        if 'status' in payload:
            if payload['status'] not in TASK_STATUSES or payload['status'] not in TASK_TRANSITIONS.get(task.get('status'), set()):
                raise ValidationError('Invalid task status transition.')
            updates['status'] = payload['status']
        if is_owner:
            if 'title' in payload:
                updates['title'] = require_string(payload, 'title', max_length=160)
            if 'description' in payload:
                updates['description'] = require_string(payload, 'description', max_length=5000)
            if 'priority' in payload:
                if payload['priority'] not in TASK_PRIORITIES:
                    raise ValidationError('priority is invalid.')
                updates['priority'] = payload['priority']
            if 'assigneeId' in payload:
                assignee_id = require_string(payload, 'assigneeId')
                if not self._is_member(project, assignee_id):
                    raise ValidationError('assigneeId must be a project member.')
                updates['assigneeId'] = assignee_id
            if 'milestoneId' in payload:
                milestone_id = require_string(payload, 'milestoneId', max_length=128)
                milestone = self.repository.get_milestone(project_id, milestone_id)
                if milestone is None or milestone.get('status') == 'COMPLETED':
                    raise ValidationError('milestoneId must reference an active milestone in this project.')
                updates['milestoneId'] = milestone_id
            if 'dueDate' in payload:
                updates['dueDate'] = self._optional_string(payload, 'dueDate')
        if not updates:
            raise ValidationError('At least one task field is required.')
        now = datetime.now(timezone.utc).isoformat()
        updates['updatedAt'] = now
        activities: list[dict[str, Any]] = []
        if 'assigneeId' in updates and updates['assigneeId'] != task.get('assigneeId'):
            activities.append(self._activity(project_id, 'TASK_ASSIGNED', identity.user_id, now, task_id=task_id))
        if 'status' in updates and updates['status'] != task.get('status'):
            activities.append(self._activity(project_id, 'TASK_STATUS_CHANGED', identity.user_id, now, task_id=task_id))
            if updates['status'] == 'COMPLETED':
                activities.append(self._activity(project_id, 'TASK_COMPLETED', identity.user_id, now, task_id=task_id))
        updated = self.repository.update_task(task, updates, activities)
        all_tasks = self.repository.list_all_tasks(project_id)
        return self._task_response(updated, [updated if item.get('taskId') == task_id else item for item in all_tasks])

    def delete_task(self, identity: AuthenticatedIdentity, project_id: str, task_id: str) -> None:
        self._require_owner(identity, project_id)
        task = self.repository.get_task(project_id, task_id)
        if task is None:
            raise NotFoundError('Task not found.')
        self.repository.delete_task(task)

    @staticmethod
    def _is_overdue(task: Mapping[str, Any], now: datetime) -> bool:
        due_date = task.get('dueDate')
        if not isinstance(due_date, str) or task.get('status') == 'COMPLETED':
            return False
        try:
            parsed = datetime.fromisoformat(due_date.replace('Z', '+00:00'))
            if parsed.tzinfo is None:
                parsed = parsed.replace(tzinfo=timezone.utc)
            return parsed < now
        except ValueError:
            return False

    def _team(self, project: ProjectItem) -> list[dict[str, Any]]:
        owner_id = project.get('ownerId')
        members: list[dict[str, Any]] = []
        if owner_id:
            members.append({'userId': owner_id, 'role': 'Owner', 'joinedAt': project.get('createdAt')})
        members.extend(
            {key: value for key, value in item.items() if key not in {'PK', 'SK'}}
            for item in self.repository.list_members(project['id'])
        )
        return members

    def progress(self, identity: AuthenticatedIdentity, project_id: str) -> dict[str, Any]:
        project = self._require_project_access(identity, project_id)
        milestones = self.repository.list_all_milestones(project_id)
        tasks = self.repository.list_all_tasks(project_id)
        now = datetime.now(timezone.utc)
        completed_tasks = sum(1 for task in tasks if task.get('status') == 'COMPLETED')
        task_counts = {
            'todo': sum(1 for task in tasks if task.get('status') == 'TODO'),
            'inProgress': sum(1 for task in tasks if task.get('status') == 'IN_PROGRESS'),
            'inReview': sum(1 for task in tasks if task.get('status') == 'IN_REVIEW'),
            'completed': completed_tasks,
        }
        completed_milestones = sum(1 for milestone in milestones if milestone.get('status') == 'COMPLETED')
        member_stats: list[dict[str, Any]] = []
        activities = self.repository.list_all_activity(project_id)
        for member in self._team(project):
            user_id = member.get('userId')
            assigned = [task for task in tasks if task.get('assigneeId') == user_id]
            member_stats.append({
                'userId': user_id,
                'role': member.get('role'),
                'assignedTasks': len(assigned),
                'completedTasks': sum(1 for task in assigned if task.get('status') == 'COMPLETED'),
                'inReviewTasks': sum(1 for task in assigned if task.get('status') == 'IN_REVIEW'),
                'activityCount': sum(1 for activity in activities if activity.get('actorId') == user_id),
            })
        milestone_stats = []
        for milestone in milestones:
            milestone_tasks = [task for task in tasks if task.get('milestoneId') == milestone.get('milestoneId')]
            completed = sum(1 for task in milestone_tasks if task.get('status') == 'COMPLETED')
            total = len(milestone_tasks)
            milestone_stats.append({
                'milestoneId': milestone.get('milestoneId'), 'title': milestone.get('title'),
                'status': milestone.get('status'), 'totalTasks': total, 'completedTasks': completed,
                'percentage': int(round(completed / total * 100)) if total else 0,
            })
        return {
            'projectId': project_id,
            'totalMilestones': len(milestones),
            'completedMilestones': completed_milestones,
            'totalTasks': len(tasks),
            'completedTasks': completed_tasks,
            'inProgressTasks': task_counts['inProgress'],
            'tasksInReview': task_counts['inReview'],
            'todoTasks': task_counts['todo'],
            'overdueTasks': sum(1 for task in tasks if self._is_overdue(task, now)),
            'overallCompletionPercentage': int(round(completed_tasks / len(tasks) * 100)) if tasks else 0,
            'milestones': milestone_stats,
            'members': member_stats,
        }

    def activity(self, identity: AuthenticatedIdentity, project_id: str, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], str | None]:
        self._require_project_access(identity, project_id)
        if not 1 <= limit <= 100:
            raise ValidationError('limit must be between 1 and 100.')
        items, next_cursor = self.repository.list_activity(project_id, limit, cursor)
        return [_collaboration_response(item) for item in items], next_cursor

    def contributions(self, identity: AuthenticatedIdentity, project_id: str, member_id: str) -> dict[str, Any]:
        project = self._require_project_access(identity, project_id)
        team_ids = {member.get('userId') for member in self._team(project)}
        if member_id not in team_ids:
            raise NotFoundError('Member not found.')
        if identity.user_id != project.get('ownerId') and identity.user_id != member_id:
            raise ForbiddenError('You cannot view another member contribution summary.')
        tasks = [task for task in self.repository.list_all_tasks(project_id) if task.get('assigneeId') == member_id]
        completed_ids = [task['taskId'] for task in tasks if task.get('status') == 'COMPLETED']
        activities = [activity for activity in self.repository.list_all_activity(project_id) if activity.get('actorId') == member_id]
        verified = [item for item in self.repository.list_contributions(project_id) if item.get('userId') == member_id]
        return {
            'projectId': project_id, 'userId': member_id, 'assignedTasks': len(tasks),
            'completedTasks': len(completed_ids), 'inReviewTasks': sum(1 for task in tasks if task.get('status') == 'IN_REVIEW'),
            'activityCount': len(activities), 'completedTaskIds': completed_ids,
            'verifiedContribution': bool(verified), 'contributionRecords': [_collaboration_response(item) for item in verified],
        }

    def _public_contribution(self, item: Mapping[str, Any], project: ProjectItem, *, include_private: bool) -> dict[str, Any]:
        membership = self.repository.get_membership(str(project.get('id')), str(item.get('userId')))
        result: dict[str, Any] = {
            'contributionId': item.get('contributionId'), 'projectId': project.get('id'),
            'projectTitle': project.get('title'), 'projectDescription': project.get('description'),
            'userId': item.get('userId'), 'verifiedCompletion': item.get('verifiedCompletion') is True,
            'completedTaskCount': item.get('completedTaskCount', 0), 'completionTimestamp': item.get('completionTimestamp'),
            'role': 'Owner' if project.get('ownerId') == item.get('userId') else (membership or {}).get('role', 'Contributor'),
        }
        if include_private:
            result['completedTaskIds'] = list(item.get('completedTaskIds', []))
        return result

    def user_contributions(self, identity: AuthenticatedIdentity, user_id: str, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], str | None]:
        if not user_id or len(user_id) > 256:
            raise ValidationError('userId is invalid.')
        if not 1 <= limit <= 100:
            raise ValidationError('limit must be between 1 and 100.')
        include_private = identity.user_id == user_id
        records, next_cursor = self.repository.list_user_contributions(user_id, limit, cursor)
        results: list[dict[str, Any]] = []
        for record in records:
            project = self.repository.get_project(record['projectId'])
            if project is None:
                continue
            if project.get('visibility', 'public') != 'public' and not include_private:
                continue
            results.append(self._public_contribution(record, project, include_private=include_private))
        return results, next_cursor

    def completed_projects(self, identity: AuthenticatedIdentity, user_id: str, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], str | None]:
        contributions, next_cursor = self.user_contributions(identity, user_id, limit, cursor)
        projects = []
        for contribution in contributions:
            project = self.repository.get_project(contribution['projectId'])
            if not project or project.get('status') != 'COMPLETED':
                continue
            projects.append({
                'projectId': contribution['projectId'], 'title': contribution.get('projectTitle'),
                'description': contribution.get('projectDescription'), 'status': 'COMPLETED',
                'completedAt': contribution.get('completionTimestamp'), 'role': contribution.get('role'),
                'verifiedContribution': contribution.get('verifiedCompletion') is True,
                'completedTaskCount': contribution.get('completedTaskCount', 0),
                'repositoryUrl': project.get('repositoryUrl'),
            })
        return projects, next_cursor

    def _completion_requirements(self, project: ProjectItem, project_id: str) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
        if project.get('status') == 'COMPLETED':
            raise ConflictError('Project is already completed.')
        if project.get('status') not in {'Recruiting', 'ACTIVE', 'IN_PROGRESS'}:
            raise ConflictError('Project is not active.')
        milestones = self.repository.list_all_milestones(project_id)
        tasks = self.repository.list_all_tasks(project_id)
        if any(milestone.get('status') != 'COMPLETED' for milestone in milestones):
            raise ConflictError('All milestones must be completed before submission.')
        now = datetime.now(timezone.utc)
        if any(task.get('status') != 'COMPLETED' for task in tasks) or any(self._is_overdue(task, now) for task in tasks):
            raise ConflictError('All project tasks must be completed before submission.')
        return milestones, tasks, self.progress(AuthenticatedIdentity(project['ownerId']), project_id)

    @staticmethod
    def _contribution_items(project_id: str, tasks: list[Mapping[str, Any]], completed_at: str) -> list[dict[str, Any]]:
        by_user: dict[str, list[str]] = {}
        for task in tasks:
            user_id = task.get('assigneeId')
            if task.get('status') == 'COMPLETED' and isinstance(user_id, str):
                by_user.setdefault(user_id, []).append(task['taskId'])
        return [{
            'PK': f'PROJECT#{project_id}', 'SK': f'CONTRIBUTION#{user_id}', 'entityType': 'contribution',
            'contributionId': f'contribution-{project_id}-{user_id}', 'projectId': project_id, 'userId': user_id,
            'verifiedCompletion': True, 'completedTaskIds': task_ids, 'completedTaskCount': len(task_ids),
            'completionTimestamp': completed_at,
            'GSI1PK': f'USER#{user_id}#CONTRIBUTIONS', 'GSI1SK': f'{completed_at}#{project_id}#{user_id}',
        } for user_id, task_ids in by_user.items()]

    def submit_completion(self, identity: AuthenticatedIdentity, project_id: str) -> dict[str, Any]:
        project = self._require_owner(identity, project_id)
        if self.repository.get_completion(project_id) is not None:
            raise ConflictError('A completion submission already exists.')
        _, tasks, progress = self._completion_requirements(project, project_id)
        now = datetime.now(timezone.utc).isoformat()
        team = self._team(project)
        completion: dict[str, Any] = {
            'PK': f'PROJECT#{project_id}', 'SK': self.repository.COMPLETION_KEY, 'entityType': 'completion',
            'projectId': project_id, 'status': 'PENDING_CONFIRMATION', 'submittedBy': identity.user_id,
            'submittedAt': now, 'progressSnapshot': progress, 'teamSnapshot': team,
        }
        owner_confirmation = {
            'PK': f'PROJECT#{project_id}', 'SK': f'{self.repository.CONFIRMATION_PREFIX}{identity.user_id}',
            'entityType': 'confirmation', 'projectId': project_id, 'userId': identity.user_id,
            'status': 'CONFIRMED', 'createdAt': now,
        }
        if len(team) == 1:
            completed = dict(completion)
            completed['status'] = 'COMPLETED'
            completed['completedAt'] = now
            self.repository.create_and_finalize_completion(
                project, completed, owner_confirmation,
                self._activity(project_id, 'PROJECT_COMPLETION_SUBMITTED', identity.user_id, now),
                self._activity(project_id, 'PROJECT_COMPLETION_CONFIRMED', identity.user_id, now),
                self._contribution_items(project_id, tasks, now),
            )
            completion = completed
        else:
            self.repository.create_completion(completion, owner_confirmation, self._activity(project_id, 'PROJECT_COMPLETION_SUBMITTED', identity.user_id, now))
        return _collaboration_response(completion)

    def get_completion(self, identity: AuthenticatedIdentity, project_id: str) -> dict[str, Any]:
        project = self._require_project_access(identity, project_id)
        completion = self.repository.get_completion(project_id)
        if completion is None:
            raise NotFoundError('Completion submission not found.')
        return {**_collaboration_response(completion), 'confirmations': [_collaboration_response(item) for item in self.repository.list_confirmations(project_id)], 'teamSize': len(self._team(project))}

    def confirm_completion(self, identity: AuthenticatedIdentity, project_id: str) -> dict[str, Any]:
        project = self._require_project_access(identity, project_id)
        completion = self.repository.get_completion(project_id)
        if completion is None:
            raise NotFoundError('Completion submission not found.')
        if completion.get('status') != 'PENDING_CONFIRMATION':
            raise ConflictError('Completion is not awaiting confirmation.')
        team = self._team(project)
        if identity.user_id not in {member.get('userId') for member in team}:
            raise ForbiddenError('Only current project members can confirm.')
        now = datetime.now(timezone.utc).isoformat()
        confirmation = {
            'PK': f'PROJECT#{project_id}', 'SK': f'{self.repository.CONFIRMATION_PREFIX}{identity.user_id}',
            'entityType': 'confirmation', 'projectId': project_id, 'userId': identity.user_id,
            'status': 'CONFIRMED', 'createdAt': now,
        }
        confirmations = self.repository.list_confirmations(project_id)
        confirmed_ids = {item.get('userId') for item in confirmations if item.get('status') == 'CONFIRMED'} | {identity.user_id}
        finalize = all(member.get('userId') in confirmed_ids for member in team)
        tasks = self.repository.list_all_tasks(project_id)
        activity = self._activity(project_id, 'PROJECT_COMPLETION_CONFIRMED', identity.user_id, now)
        self.repository.confirm_completion(project, completion, confirmation, finalize=finalize, contributions=self._contribution_items(project_id, tasks, now), activity=activity)
        return {'projectId': project_id, 'status': 'COMPLETED' if finalize else 'PENDING_CONFIRMATION', 'confirmedMembers': len(confirmed_ids), 'requiredMembers': len(team)}

    def reject_completion(self, identity: AuthenticatedIdentity, project_id: str, body: Any) -> dict[str, Any]:
        project = self._require_project_access(identity, project_id)
        if identity.user_id == project.get('ownerId'):
            raise ForbiddenError('The submitting owner cannot reject their own submission.')
        completion = self.repository.get_completion(project_id)
        if completion is None:
            raise NotFoundError('Completion submission not found.')
        if completion.get('status') != 'PENDING_CONFIRMATION':
            raise ConflictError('Completion is not awaiting confirmation.')
        if identity.user_id not in {member.get('userId') for member in self._team(project)}:
            raise ForbiddenError('Only current project members can reject.')
        payload = require_json_object(body)
        reason = require_string(payload, 'reason', max_length=1000)
        now = datetime.now(timezone.utc).isoformat()
        self.repository.reject_completion(project_id, identity.user_id, reason, now, self._activity(project_id, 'PROJECT_COMPLETION_REJECTED', identity.user_id, now))
        return {'projectId': project_id, 'status': 'REJECTED', 'reason': reason}


